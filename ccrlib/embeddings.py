"""Embedding provider for the `embedding` routing baseline.

Three modes, by precedence — the live instance stays the source of truth AND the result is
reproducible offline:

  1. LIVE (canonical). If AZURE_OPENAI_EMBEDDINGS_ENDPOINT / _DEPLOYMENT are set, every
     embedding is computed by the REAL Azure OpenAI `text-embedding-3-small` instance
     (managed-identity auth) — this is the run the paper reports — and *recorded* into the
     on-disk cache as a side effect.
  2. CACHE replay. If AOAI is NOT configured but data/embedding_cache.json exists, vectors
     are replayed from it — reproduces the live numbers offline, with no Azure and no
     model-version dependency.
  3. HASH fallback. Neither — the dependency-free hashing embedding (domain.embed), for a
     fully hermetic run that simply does not exercise the semantic baseline.

The cache is a *recording* of a live run, never a substitute: `verify()` re-queries the
real model and confirms the cached vectors still match (cosine ~ 1), so committed vectors
cannot be silently fabricated — a reviewer with AOAI access re-checks them. Embedding
models are deterministic per model version (no sampling), so the live run is
reproducible-as-reported with the version pinned (deployment + api-version).
"""
from __future__ import annotations

import json
import math
import os

from . import domain

# Sits next to agents.json / tasks.json so it is committable (and found in both the repo
# checkout and a vendored copy). Generated by a LIVE run; commit it for offline replay.
_CACHE_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                           "data", "embedding_cache.json")

_MEM: dict[str, tuple] = {}      # per-process memo (text -> vector)
_DISK: dict | None = None         # lazily-loaded on-disk cache (text -> list)
_client = None


def _use_aoai() -> bool:
    return bool(os.environ.get("AZURE_OPENAI_EMBEDDINGS_ENDPOINT")
                and os.environ.get("AZURE_OPENAI_EMBEDDINGS_DEPLOYMENT"))


def _disk() -> dict:
    global _DISK
    if _DISK is None:
        try:
            with open(_CACHE_PATH, encoding="utf-8") as f:
                _DISK = json.load(f)
        except (OSError, ValueError):
            _DISK = {}
    return _DISK


def _record(text: str, vec: tuple) -> None:
    d = _disk()
    d[text] = list(vec)
    try:  # best-effort: populates the committable cache locally; a no-op on the read-only
        os.makedirs(os.path.dirname(_CACHE_PATH), exist_ok=True)   # cloud app filesystem.
        with open(_CACHE_PATH, "w", encoding="utf-8") as f:
            json.dump(d, f)
    except OSError:
        pass


def _aoai_client():
    global _client
    if _client is None:
        from azure.identity import DefaultAzureCredential, get_bearer_token_provider
        from openai import AzureOpenAI
        _client = AzureOpenAI(
            azure_endpoint=os.environ["AZURE_OPENAI_EMBEDDINGS_ENDPOINT"],
            azure_ad_token_provider=get_bearer_token_provider(
                DefaultAzureCredential(), "https://cognitiveservices.azure.com/.default"),
            api_version=os.environ.get("AZURE_OPENAI_API_VERSION", "2024-10-21"),
        )
    return _client


def _aoai_embed(text: str) -> list[float]:
    deployment = os.environ["AZURE_OPENAI_EMBEDDINGS_DEPLOYMENT"]
    return _aoai_client().embeddings.create(model=deployment, input=text).data[0].embedding


def embed(text: str) -> tuple[float, ...]:
    """Return an embedding for `text` (process-memoized). LIVE if AOAI is configured (and
    recorded to the cache); else CACHE replay if available; else the hash fallback."""
    if text in _MEM:
        return _MEM[text]
    if _use_aoai():
        try:
            vec = tuple(_aoai_embed(text))   # LIVE — canonical, real instance
        except Exception as e:               # noqa: BLE001 — re-raise with a fix hint
            if "401" in str(e) or "PermissionDenied" in str(e) or "Forbidden" in str(e):
                raise RuntimeError(
                    "Azure OpenAI returned 401/PermissionDenied for embeddings. Grant your "
                    "identity the 'Cognitive Services OpenAI User' role on the AOAI account "
                    "(REPRODUCE.md §2a step 2.2) and wait ~1-2 min for RBAC to propagate; or "
                    "unset AZURE_OPENAI_EMBEDDINGS_* to run with the cache/hash backend."
                ) from e
            raise
        _record(text, vec)                   # record into the committable cache
    elif text in _disk():
        vec = tuple(_disk()[text])        # CACHE replay (offline reproduction)
    else:
        vec = tuple(domain.embed(text))   # HASH fallback (hermetic)
    _MEM[text] = vec
    return vec


def cosine(a, b) -> float:
    """Full cosine similarity (real AOAI vectors are not pre-normalized like domain.embed)."""
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a)) or 1.0
    nb = math.sqrt(sum(y * y for y in b)) or 1.0
    return dot / (na * nb)


def backend() -> str:
    if _use_aoai():
        return "azure_openai"
    return "embedding_cache" if _disk() else "hash_bow"


def verify(tolerance: float = 1e-4) -> dict:
    """Re-query the LIVE model for every cached text and confirm the cached vector still
    matches (cosine >= 1 - tolerance). Proves the committed cache faithfully records the
    real instance — it was not hand-crafted. Requires AOAI to be configured."""
    if not _use_aoai():
        raise SystemExit("verify needs AOAI configured (set AZURE_OPENAI_EMBEDDINGS_*).")
    d = _disk()
    if not d:
        raise SystemExit(f"no cache to verify at {_CACHE_PATH}.")
    mismatches = []
    for text, cached in d.items():
        sim = cosine(cached, _aoai_embed(text))
        if sim < 1.0 - tolerance:
            mismatches.append({"text": text[:60], "cosine": round(sim, 6)})
    return {"cached_texts": len(d), "tolerance": tolerance,
            "mismatches": mismatches, "ok": not mismatches}


def main():
    import argparse
    ap = argparse.ArgumentParser(description="Embedding provider — show backend / verify cache.")
    ap.add_argument("--verify", action="store_true",
                    help="re-query AOAI and confirm the committed cache matches the live model")
    args = ap.parse_args()
    if args.verify:
        r = verify()
        print(json.dumps(r, indent=2))
        raise SystemExit(0 if r["ok"] else 1)
    print(f"backend: {backend()} | cache: {_CACHE_PATH} ({len(_disk())} entries)")


if __name__ == "__main__":
    main()
